-- Invoked statement-by-statement in one Python connector transaction.
-- Parameters are supplied by the runner. Temporary STG_* tables are session scoped.
UPDATE DIM_CUSTOMER D SET VALID_TO=%(upper)s::TIMESTAMP_TZ, IS_CURRENT=FALSE
 FROM STG_CUSTOMERS S WHERE D.CUSTOMER_ID=S.CUSTOMER_ID AND D.IS_CURRENT
 AND D.ATTR_HASH <> SHA2(TO_JSON(ARRAY_CONSTRUCT(S.CITY,S.LOYALTY_TIER,S.IS_DELETED)),256);
INSERT INTO DIM_CUSTOMER (CUSTOMER_ID,CITY,LOYALTY_TIER,ATTR_HASH,VALID_FROM,IS_CURRENT,IS_DELETED)
 SELECT S.CUSTOMER_ID,S.CITY,S.LOYALTY_TIER,SHA2(TO_JSON(ARRAY_CONSTRUCT(S.CITY,S.LOYALTY_TIER,S.IS_DELETED)),256),
 %(upper)s::TIMESTAMP_TZ,TRUE,S.IS_DELETED FROM STG_CUSTOMERS S
 WHERE NOT EXISTS (SELECT 1 FROM DIM_CUSTOMER D WHERE D.CUSTOMER_ID=S.CUSTOMER_ID AND D.IS_CURRENT);
MERGE INTO DIM_PRODUCT D USING STG_PRODUCTS S ON D.PRODUCT_ID=S.PRODUCT_ID
 WHEN MATCHED THEN UPDATE SET D.PRODUCT_NAME=S.PRODUCT_NAME,D.CATEGORY=S.CATEGORY,D.IS_DELETED=S.IS_DELETED
 WHEN NOT MATCHED THEN INSERT (PRODUCT_ID,PRODUCT_NAME,CATEGORY,IS_DELETED) VALUES(S.PRODUCT_ID,S.PRODUCT_NAME,S.CATEGORY,S.IS_DELETED);
MERGE INTO DIM_DATE D USING (SELECT DISTINCT TO_DATE(ORDERED_AT) AS DATE_KEY FROM STG_ORDERS) S ON D.DATE_KEY=S.DATE_KEY
 WHEN NOT MATCHED THEN INSERT VALUES(S.DATE_KEY,YEAR(S.DATE_KEY),MONTH(S.DATE_KEY),DAY(S.DATE_KEY));
MERGE INTO FACT_ORDERS D USING (SELECT O.*, C.CUSTOMER_SK FROM STG_ORDERS O JOIN DIM_CUSTOMER C ON O.CUSTOMER_ID=C.CUSTOMER_ID AND C.IS_CURRENT) S ON D.ORDER_ID=S.ORDER_ID
 WHEN MATCHED THEN UPDATE SET D.DATE_KEY=TO_DATE(S.ORDERED_AT),D.STATUS=S.STATUS,D.IS_DELETED=S.IS_DELETED
 WHEN NOT MATCHED THEN INSERT VALUES(S.ORDER_ID,S.CUSTOMER_SK,TO_DATE(S.ORDERED_AT),S.STATUS,S.IS_DELETED);
MERGE INTO FACT_SALES D USING (SELECT S.*,O.CUSTOMER_SK FROM STG_SALES S JOIN FACT_ORDERS O ON S.ORDER_ID=O.ORDER_ID) S
 ON D.ORDER_ID=S.ORDER_ID AND D.LINE_ID=S.LINE_ID
 WHEN MATCHED THEN UPDATE SET D.PRODUCT_ID=S.PRODUCT_ID,D.QUANTITY=S.QUANTITY,D.LINE_REVENUE=S.LINE_REVENUE,D.IS_DELETED=S.IS_DELETED
 WHEN NOT MATCHED THEN INSERT VALUES(S.ORDER_ID,S.LINE_ID,S.CUSTOMER_SK,S.PRODUCT_ID,S.QUANTITY,S.LINE_REVENUE,S.IS_DELETED);
MERGE INTO FACT_PAYMENTS D USING STG_PAYMENTS S ON D.PAYMENT_ID=S.PAYMENT_ID
 WHEN MATCHED THEN UPDATE SET D.ORDER_ID=S.ORDER_ID,D.AMOUNT=S.AMOUNT,D.STATUS=S.STATUS,D.IS_DELETED=S.IS_DELETED
 WHEN NOT MATCHED THEN INSERT VALUES(S.PAYMENT_ID,S.ORDER_ID,S.AMOUNT,S.STATUS,S.IS_DELETED);
DELETE FROM WATERMARKS WHERE DATASET IN ('orders','order_items','payments','products','customers');
INSERT INTO WATERMARKS SELECT COLUMN1,%(upper)s::TIMESTAMP_TZ FROM VALUES ('orders'),('order_items'),('payments'),('products'),('customers');
INSERT INTO BATCH_LEDGER VALUES (%(batch)s,%(upper)s::TIMESTAMP_TZ,%(hash)s);
