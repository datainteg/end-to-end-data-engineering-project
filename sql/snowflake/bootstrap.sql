CREATE TABLE IF NOT EXISTS BATCH_LEDGER (BATCH_ID VARCHAR, UPPER_UTC TIMESTAMP_TZ, MANIFEST_HASH VARCHAR);
CREATE TABLE IF NOT EXISTS WATERMARKS (DATASET VARCHAR, UPPER_UTC TIMESTAMP_TZ);
CREATE TABLE IF NOT EXISTS DIM_CUSTOMER (CUSTOMER_SK NUMBER AUTOINCREMENT, CUSTOMER_ID VARCHAR,
 CITY VARCHAR, LOYALTY_TIER VARCHAR, ATTR_HASH VARCHAR, VALID_FROM TIMESTAMP_TZ,
 VALID_TO TIMESTAMP_TZ, IS_CURRENT BOOLEAN, IS_DELETED BOOLEAN);
CREATE TABLE IF NOT EXISTS DIM_PRODUCT (PRODUCT_ID VARCHAR, PRODUCT_NAME VARCHAR, CATEGORY VARCHAR, IS_DELETED BOOLEAN);
CREATE TABLE IF NOT EXISTS DIM_DATE (DATE_KEY DATE, YEAR NUMBER, MONTH NUMBER, DAY NUMBER);
CREATE TABLE IF NOT EXISTS FACT_ORDERS (ORDER_ID VARCHAR, CUSTOMER_SK NUMBER, DATE_KEY DATE, STATUS VARCHAR, IS_DELETED BOOLEAN);
CREATE TABLE IF NOT EXISTS FACT_SALES (ORDER_ID VARCHAR, LINE_ID VARCHAR, CUSTOMER_SK NUMBER, PRODUCT_ID VARCHAR,
 QUANTITY NUMBER, LINE_REVENUE NUMBER(18,2), IS_DELETED BOOLEAN);
CREATE TABLE IF NOT EXISTS FACT_PAYMENTS (PAYMENT_ID VARCHAR, ORDER_ID VARCHAR, AMOUNT NUMBER(18,2), STATUS VARCHAR, IS_DELETED BOOLEAN);
CREATE OR REPLACE VIEW MART_SALES AS
 SELECT S.*, O.DATE_KEY, C.CUSTOMER_ID, C.LOYALTY_TIER AS TIER_OBSERVED_AT_FIRST_PUBLICATION
 FROM FACT_SALES S JOIN FACT_ORDERS O ON S.ORDER_ID=O.ORDER_ID
 JOIN DIM_CUSTOMER C ON S.CUSTOMER_SK=C.CUSTOMER_SK
 WHERE O.STATUS='paid' AND NOT O.IS_DELETED AND NOT S.IS_DELETED;
CREATE OR REPLACE VIEW MART_KPIS AS
 SELECT (SELECT COALESCE(SUM(LINE_REVENUE),0) FROM MART_SALES) AS NET_SALES,
 (SELECT COUNT(*) FROM FACT_ORDERS WHERE STATUS='paid' AND NOT IS_DELETED) AS PAID_ORDERS,
 NET_SALES / NULLIF(PAID_ORDERS,0) AS AOV,
 (SELECT COUNT_IF(STATUS='SUCCESS') / NULLIF(COUNT(*),0) FROM FACT_PAYMENTS WHERE NOT IS_DELETED) AS PAYMENT_SUCCESS_RATE;
